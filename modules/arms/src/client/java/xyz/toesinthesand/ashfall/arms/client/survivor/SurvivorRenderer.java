package xyz.toesinthesand.ashfall.arms.client.survivor;

import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelLayers;
import net.minecraft.client.renderer.entity.ArmorModelSet;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.EntityRenderers;
import net.minecraft.client.renderer.entity.HumanoidMobRenderer;
import net.minecraft.client.renderer.entity.layers.HumanoidArmorLayer;
import net.minecraft.client.renderer.entity.state.HumanoidRenderState;
import net.minecraft.resources.Identifier;
import xyz.toesinthesand.ashfall.arms.survivor.Survivor;
import xyz.toesinthesand.ashfall.arms.survivor.Survivors;

/**
 * Survivors drawn with the vanilla wide player model (its outer layer included: hats, jackets, sleeves) and one of
 * {@link Survivor#SKINS} original skins, {@code textures/entity/survivor/survivor_<n>.png}, generated by
 * {@code tools/textures/survivors.py}. The held weapon and any armour use the usual humanoid layers; the nameplate is
 * the entity's custom name ("Name (Role)").
 */
public class SurvivorRenderer extends HumanoidMobRenderer<Survivor, SurvivorRenderer.State, HumanoidModel<SurvivorRenderer.State>> {
	private static final Identifier[] SKINS = new Identifier[Survivor.SKINS];

	static {
		for (int i = 0; i < SKINS.length; i++) {
			SKINS[i] = Identifier.fromNamespaceAndPath("ashfall", "textures/entity/survivor/survivor_" + i + ".png");
		}
	}

	public SurvivorRenderer(EntityRendererProvider.Context context) {
		super(context, new HumanoidModel<>(context.bakeLayer(ModelLayers.PLAYER)), 0.5f);
		addLayer(new HumanoidArmorLayer<>(this, ArmorModelSet.bake(ModelLayers.PLAYER_ARMOR, context.getModelSet(), HumanoidModel::new),
				context.getEquipmentRenderer()));
	}

	public static void register() {
		EntityRenderers.register(Survivors.SURVIVOR, SurvivorRenderer::new);
	}

	@Override
	public State createRenderState() {
		return new State();
	}

	@Override
	public void extractRenderState(Survivor survivor, State state, float partialTick) {
		super.extractRenderState(survivor, state, partialTick);
		state.skin = survivor.skin();
	}

	@Override
	public Identifier getTextureLocation(State state) {
		return SKINS[Math.floorMod(state.skin, SKINS.length)];
	}

	/** The humanoid state plus which skin to draw. */
	public static class State extends HumanoidRenderState {
		public int skin;
	}
}
